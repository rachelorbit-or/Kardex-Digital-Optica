"""Pruebas de validaciones.py.  Ejecutar:  python tests/test_validaciones.py"""

from utilidades_prueba import verificar, titulo, resumen
import validaciones as v

titulo("DNI y telefono")
verificar("DNI 70123456 es valido", v.validar_dni("70123456"))
verificar("DNI de 7 digitos es invalido", not v.validar_dni("7012345"))
verificar("DNI de 9 digitos es invalido", not v.validar_dni("701234567"))
verificar("DNI con letras es invalido", not v.validar_dni("7012345A"))
verificar("DNI vacio es invalido", not v.validar_dni(""))
verificar("telefono 987654321 es valido", v.validar_telefono("987654321"))
verificar("telefono de 5 digitos es invalido", not v.validar_telefono("98765"))
verificar("telefono con guion es invalido", not v.validar_telefono("987-654-32"))

titulo("Nombre y texto")
verificar("'Quispe Rojas, Ana' es valido", v.validar_nombre_completo("Quispe Rojas, Ana"))
verificar("nombre sin coma es invalido", not v.validar_nombre_completo("Quispe Rojas Ana"))
verificar("nombre con dos comas es invalido", not v.validar_nombre_completo("Quispe, Rojas, Ana"))
verificar("nombre sin apellidos es invalido", not v.validar_nombre_completo(", Ana"))
verificar("nombre sin nombres es invalido", not v.validar_nombre_completo("Quispe Rojas,"))
verificar("nombre con ';' es invalido", not v.validar_nombre_completo("Quispe; Rojas, Ana"))
verificar("texto 'Policarbonato' es valido", v.validar_texto("Policarbonato"))
verificar("texto con solo espacios es invalido", not v.validar_texto("   "))
verificar("texto con ';' es invalido", not v.validar_texto("CR;39"))

titulo("Edad y distancia interpupilar")
verificar("edad 34 es valida", v.validar_edad("34"))
verificar("edad 1 es valida (limite)", v.validar_edad("1"))
verificar("edad 110 es valida (limite)", v.validar_edad("110"))
verificar("edad 0 es invalida", not v.validar_edad("0"))
verificar("edad 111 es invalida", not v.validar_edad("111"))
verificar("edad -5 es invalida", not v.validar_edad("-5"))
verificar("edad 'abc' es invalida", not v.validar_edad("abc"))
verificar("DIP 62 es valida", v.validar_dip("62"))
verificar("DIP 40 y 80 son validas (limites)", v.validar_dip("40") and v.validar_dip("80"))
verificar("DIP 39 y 81 son invalidas", not v.validar_dip("39") and not v.validar_dip("81"))

titulo("Medida de un ojo (esfera/cilindro/eje)")
verificar("'-2.00/-1.00/90' es valida", v.validar_medida_ojo("-2.00/-1.00/90"))
verificar("'+1.50/0/0' es valida", v.validar_medida_ojo("+1.50/0/0"))
verificar("coma decimal '-1,50/-0,75/180' es valida", v.validar_medida_ojo("-1,50/-0,75/180"))
verificar("cilindro 6 es valido (limite)", v.validar_medida_ojo("0/-6/0"))
verificar("cilindro 6.25 es invalido", not v.validar_medida_ojo("0/-6.25/0"))
verificar("cilindro 7 es invalido", not v.validar_medida_ojo("0/7/0"))
verificar("esfera 20 es valida (limite)", v.validar_medida_ojo("20/0/0"))
verificar("esfera 21 es invalida", not v.validar_medida_ojo("21/0/0"))
verificar("eje 180 es valido (limite)", v.validar_medida_ojo("0/-1/180"))
verificar("eje 181 es invalido", not v.validar_medida_ojo("0/-1/181"))
verificar("eje negativo es invalido", not v.validar_medida_ojo("0/-1/-5"))
verificar("medida con 2 partes es invalida", not v.validar_medida_ojo("-2.00/-1.00"))
verificar("medida con 4 partes es invalida", not v.validar_medida_ojo("1/2/3/4"))
verificar("medida con letras es invalida", not v.validar_medida_ojo("abc/0/0"))
verificar("medida vacia es invalida", not v.validar_medida_ojo(""))
verificar("'nan' no se acepta como numero", not v.validar_medida_ojo("nan/0/0"))
verificar("'inf' no se acepta como numero", not v.validar_medida_ojo("inf/0/0"))

titulo("Fecha")
verificar("05/10/2026 es valida", v.validar_fecha("05/10/2026"))
verificar("29/02/2028 es valida (anio bisiesto)", v.validar_fecha("29/02/2028"))
verificar("29/02/2027 es invalida (no bisiesto)", not v.validar_fecha("29/02/2027"))
verificar("31/04/2026 es invalida (abril tiene 30)", not v.validar_fecha("31/04/2026"))
verificar("32/01/2026 es invalida", not v.validar_fecha("32/01/2026"))
verificar("10/13/2026 es invalida (mes 13)", not v.validar_fecha("10/13/2026"))
verificar("2026-10-05 es invalida (formato)", not v.validar_fecha("2026-10-05"))
verificar("5/10/2026 es invalida (falta el cero)", not v.validar_fecha("5/10/2026"))
verificar("anio 1999 es invalido", not v.validar_fecha("05/10/1999"))

titulo("Utilidades de texto")
verificar("normalizar quita tildes y mayusculas", v.normalizar_texto("  PÉREZ Núñez ") == "perez nunez")
verificar("apellido_de('Quispe Rojas, Ana') = 'Quispe Rojas'", v.apellido_de("Quispe Rojas, Ana") == "Quispe Rojas")
verificar("es_solo_digitos('123') es True y ('12a') es False", v.es_solo_digitos("123") and not v.es_solo_digitos("12a"))

resumen()
